export const HEXAGRAM_BY_INDEX: Readonly<Record<number, HexagramEntry>> =
  Object.fromEntries(HEXAGRAMS.map((h) => [h.index, h]));

/** key: `${upper}/${lower}` */
export const HEXAGRAM_BY_UPPER_LOWER: Readonly<
  Record<string, HexagramEntry>
> = Object.fromEntries(
  HEXAGRAMS.map((h) => [`${h.upper}/${h.lower}`, h]),
);

/** key: binary.join("") 六位自下而上 */
export const HEXAGRAM_BY_BINARY: Readonly<Record<string, HexagramEntry>> =
  Object.fromEntries(HEXAGRAMS.map((h) => [h.binary.join(""), h]));

export function getHexagram(index: number): HexagramEntry | undefined {
  return HEXAGRAM_BY_INDEX[index];
}

export function getHexagramByTrigrams(
  upper: TrigramName,
  lower: TrigramName,
): HexagramEntry | undefined {
  return HEXAGRAM_BY_UPPER_LOWER[`${upper}/${lower}`];
}

export function getHexagramByBinary(
  binary: HexagramEntry["binary"] | string,
): HexagramEntry | undefined {
  const key = typeof binary === "string" ? binary : binary.join("");
  return HEXAGRAM_BY_BINARY[key];
}
