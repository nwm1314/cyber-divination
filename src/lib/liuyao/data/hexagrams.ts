/**
 * 六十四卦表（文王序 1–64）
 * 来源见 sources.ts；卦辞/爻辞为通行本意中性摘要。
 * binary：自下而上六爻，1=阳 0=阴；与 upper/lower 经卦组合一致。
 */

import type { HexagramEntry, TrigramName } from "@/lib/types/liuyao";
import { TRIGRAM_BY_NAME } from "./trigrams";

function bin(
  lower: TrigramName,
  upper: TrigramName,
): HexagramEntry["binary"] {
  const lo = TRIGRAM_BY_NAME[lower].binary;
  const up = TRIGRAM_BY_NAME[upper].binary;
  return [lo[0], lo[1], lo[2], up[0], up[1], up[2]] as HexagramEntry["binary"];
}

function entry(
  index: number,
  name: string,
  shortName: string,
  upper: TrigramName,
  lower: TrigramName,
  guaci: string,
  yaoci: HexagramEntry["yaoci"],
): HexagramEntry {
  return {
    index,
    name,
    shortName,
    upper,
    lower,
    binary: bin(lower, upper),
    guaci,
    yaoci,
  };
}

