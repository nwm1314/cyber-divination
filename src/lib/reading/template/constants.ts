/** 调候提示（《穷通宝典》原则 + 日干×月令摘要表） */
export function tiaohouHint(dayMaster: string, monthBranch: string): string {
  const meta = STEM_META[dayMaster];
  const season = BRANCH_SEASON[monthBranch] ?? "当令之月";
  const key = `${dayMaster}${monthBranch}`;
  const specific = TIAOHOU_TABLE[key];
  if (specific) {
    return `日主${dayMaster}生于${season}（${monthBranch}月）：${specific}。`;
  }
  // 满表后仅非法干支落入此分支；保留季节原则兜底
  if (!meta) {
    return `出生于${season}，论命首重调候（《穷通宝典》），宜结合日主与月令细参喜用。`;
  }
  const cold = ["亥", "子", "丑", "寅"].includes(monthBranch);
  const hot = ["巳", "午", "未"].includes(monthBranch);
  if (cold) {
    return `日主${dayMaster}生于${season}，寒气偏重，调候宜先见火暖局（《穷通宝典》：冬生水旺，须用火调候），再论扶抑。`;
  }
  if (hot) {
    return `日主${dayMaster}生于${season}，暑气偏重，调候宜先见水润局（《穷通宝典》：夏生火旺，须用水调候），再论扶抑。`;
  }
  return `日主${dayMaster}生于${season}，寒暖相对中和，仍须按《穷通宝典》查该日干当月调候用神是否有力。`;
}

