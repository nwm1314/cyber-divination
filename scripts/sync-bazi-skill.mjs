/**
 * 将 .claude/skills/bazi/references 同步到 src/lib/bazi/references
 * skill 为权威源，禁止业务手写第二套表。
 */
import fs from "node:fs";
import crypto from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const skillRoots = [
  path.join(root, ".agents", "skills", "bazi"),
  path.join(root, ".claude", "skills", "bazi"),
];
const skillDir = skillRoots.find((candidate) => fs.existsSync(candidate));
if (!skillDir) {
  console.error(`[sync:skill] skill source not found: ${skillRoots.join(", ")}`);
  process.exit(1);
}
const srcDir = path.join(skillDir, "references");
const destDir = path.join(root, "src", "lib", "bazi", "references");
const manifestPath = path.join(destDir, "manifest.ts");
const checkOnly = process.argv.includes("--check");

const FILES = [
  "wuxing-tables.md",
  "shichen-table.md",
  "dayun-rules.md",
  "classical-texts.md",
];

if (!fs.existsSync(srcDir)) {
  console.error(`[sync:skill] 权威源不存在: ${srcDir}`);
  process.exit(1);
}

if (!checkOnly) fs.mkdirSync(destDir, { recursive: true });

const readme = `# bazi skill references (read-only sync)

Authoritative source: the repository's bazi skill reference directory.

Do not edit this directory by hand. After updating the skill, run:

\`\`\`bash
npm run sync:skill
\`\`\`
`;

const sha256 = (file) =>
  crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");

const identityFiles = ["LICENSE", "README.md", "SKILL.md", ...FILES.map((f) => `references/${f}`)];
const files = identityFiles.map((relativePath) => {
  const absolutePath = path.join(skillDir, relativePath);
  if (!fs.existsSync(absolutePath)) {
    console.error(`[sync:skill] missing identity file: ${absolutePath}`);
    process.exit(1);
  }
  return { path: relativePath, sha256: sha256(absolutePath) };
});
const referenceHash = crypto
  .createHash("sha256")
  .update(files.map((file) => `${file.path}:${file.sha256}`).join("\n"))
  .digest("hex");
const manifest = `/** Generated by scripts/sync-bazi-skill.mjs. Do not edit by hand. */
export const BAZI_SKILL_PROVENANCE = ${JSON.stringify(
  {
    skillRef: "bazi-skill",
    source: "project-synced-skill",
    sourceLicense: "MIT",
    referenceManifestVersion: "1",
    referenceHash,
    files,
    execution: "deterministic-project-engine",
  },
  null,
  2,
)} as const;
`;

if (!checkOnly) {
  fs.writeFileSync(path.join(destDir, "README.md"), readme, "utf8");
  fs.writeFileSync(manifestPath, manifest, "utf8");
}

for (const file of FILES) {
  const from = path.join(srcDir, file);
  const to = path.join(destDir, file);
  if (!fs.existsSync(from)) {
    console.error(`[sync:skill] 缺少文件: ${from}`);
    process.exit(1);
  }
  if (checkOnly) {
    if (!fs.existsSync(to) || !crypto.timingSafeEqual(Buffer.from(sha256(from)), Buffer.from(sha256(to)))) {
      console.error(`[sync:skill] stale reference: ${file}`);
      process.exitCode = 1;
    }
  } else {
    fs.copyFileSync(from, to);
  }
  console.log(`[sync:skill] ${file}`);
}

if (checkOnly) {
  if (!fs.existsSync(manifestPath) || fs.readFileSync(manifestPath, "utf8").indexOf(referenceHash) < 0) {
    console.error("[sync:skill] stale provenance manifest");
    process.exitCode = 1;
  }
  if (process.exitCode) process.exit(1);
  console.log(`[sync:skill] check passed (${referenceHash})`);
} else {
  console.log(`[sync:skill] synced (${referenceHash}) -> ${destDir}`);
}
